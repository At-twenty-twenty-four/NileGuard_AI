export class I18nManager {
  private static currentLanguage: Language = 'en';

  static setLanguage(lang: Language): void {
    if (lang in SUPPORTED_LANGUAGES) {
      this.currentLanguage = lang;
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('language', lang);
      }
    }
  }

  static getLanguage(): Language {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('language') as Language;
      if (saved && saved in SUPPORTED_LANGUAGES) {
        this.currentLanguage = saved;
      }
    }
    return this.currentLanguage;
  }

  static t(key: string, defaultValue?: string): string {
    const lang = this.getLanguage();
    const value = translations[lang]?.[key];
    return value || defaultValue || key;
  }

  static getSupportedLanguages(): Record<Language, string> {
    return SUPPORTED_LANGUAGES;
  }

  static getCurrentLanguageLabel(): string {
    return SUPPORTED_LANGUAGES[this.getLanguage()];
  }
}
